#!/usr/bin/env python3
"""mtkloader's console font: font8x16.h from an 8x16 BDF font, ASCII 0x20-0x7e, MSB = left.

  mkfont8x16.py FONT.bdf > font8x16.h
"""
import os
import sys


def glyphs(path):
    """{code: 16 rows}, each glyph placed in the 8x16 cell by its BBX against the font's bounding box."""
    out, enc, bbx, rows = {}, None, None, None
    for line in open(path):
        w = line.split()
        if not w:
            continue
        if w[0] == 'FONTBOUNDINGBOX':
            fw, fh, fx, fy = map(int, w[1:])
            assert (fw, fh) == (8, 16), 'not an 8x16 font'
        elif w[0] == 'ENCODING':
            enc = int(w[1])
        elif w[0] == 'BBX':
            bbx = tuple(map(int, w[1:]))
        elif w[0] == 'BITMAP':
            rows = []
        elif w[0] == 'ENDCHAR':
            bw, bh, bx, by = bbx
            assert bw + bx - fx <= 8, enc
            cell = [0] * 16
            top = (fh + fy) - (bh + by)
            for i, r in enumerate(rows):
                cell[top + i] = int(r[:2], 16) >> (bx - fx)
            out[enc], rows = cell, None
        elif rows is not None:
            rows.append(w[0])
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    g = glyphs(sys.argv[1])
    print(f'/* Generated by tools/mkfont8x16.py from {os.path.basename(sys.argv[1])}: ASCII 0x20-0x7e, 8x16, MSB = left. */')
    print('static const unsigned char font8x16[95][16] = {')
    for c in range(0x20, 0x7f):
        name = chr(c) if c != 0x5c else 'backslash'
        print('    { ' + ','.join(f'0x{b:02x}' for b in g[c]) + f' }}, /* {name} */')
    print('};')


if __name__ == '__main__':
    main()
